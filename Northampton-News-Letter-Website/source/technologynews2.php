 still hovering at its highest level in 40 years, consumers have curbed their spending on many discretionary items. 
 Thats likely contributing to a recent decline in smartphone sales, although the iPhone has fared far better than 
 competing Android devices .The dimming sales outlook prompted the research firm International Data Corp. to predict a 
 worldwide decline in 2022 smartphone shipments of 6.5%, almost double the 3.5% decline it had estimated a few months 
 ago. Despite that anticipated drop in sales, the average price for new smartphones is expected to finish this year about 
 6% higher than last year, IDC estimated.By keeping iPhones prices the same, Apple faces the potential risk of 
 undermining its profits if inflation drives up its own costs. Its a hit that the company could easily afford, 
 given it has reaped $44 billion in profits through the first half of this year.Apple could also end up fatten its 
 bottom line if more consumers looking upgrade their mobile devices gravitate to the high-end Pro and Pro Max models, 
 which generate bigger profit margins than the cheaper models. And it appears Apple is anticipating a growing number of 
 consumers will will be prepared to pay an additional $200 to $300 for deluxe versions of the iPhone 14, said Wedbush 
 Securities analyst Daniel Ives.Apples stock price gained 1% Wednesday to close at $155.96.Consumers have already been 
 snapping up iPhones this year, even though Apple charges among the industrys highest prices. Apple sold an estimated 
