 Pro Max will start at $1099.Among the latest improvements is a 48-megapixel camera in the Pro and Pro Max models that 
 the company said will produce especially crisp pictures. The iPhone 13 versions of the Pro and Pro Max have 12-megapixel 
 cameras. This years high-end models will also have always-on displays that stay lit even when the device is locked, a 
 feature that has long been available on many smartphones powered by Googles Android software.Beginning in November, all 
 the iPhone 14 models will be able to send SOS messages via a new satellite feature - a safety measure intended to let 
